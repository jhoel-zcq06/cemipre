-- Esquema base de datos CEMIPRE (PostgreSQL / Supabase)
-- Nota: nunca cargar datos reales de personas atendidas mientras no estén aplicadas las migraciones de Auth y RLS (0002+).

create table if not exists public.personas (
  id bigint generated by default as identity primary key,
  codigo text not null unique check (char_length(trim(codigo)) between 1 and 32),
  nombre text not null check (char_length(trim(nombre)) between 1 and 120),
  creado timestamptz not null default now()
);

create table if not exists public.bitacoras (
  id bigint generated by default as identity primary key,
  persona_id bigint not null references public.personas(id) on delete cascade,
  titulo text not null check (char_length(trim(titulo)) between 1 and 160),
  url_docs text not null default '',
  google_doc_id text not null default '',
  -- Solo para demostración inicial sin conexión a Google Docs.
  extracto_demo text not null default '',
  orden integer not null default 0,
  actualizada timestamptz not null default now()
);

create table if not exists public.eventos (
  id bigint generated by default as identity primary key,
  titulo text not null check (char_length(trim(titulo)) between 1 and 160),
  descripcion text not null default '' check (char_length(descripcion) <= 2000),
  inicio timestamptz not null,
  fin timestamptz not null,
  responsable text not null default 'Equipo CEMIPRE' check (char_length(trim(responsable)) between 1 and 120),
  creado timestamptz not null default now(),
  constraint eventos_rango_valido check (fin > inicio)
);

create table if not exists public.actividad (
  id bigint generated by default as identity primary key,
  descripcion text not null check (char_length(trim(descripcion)) between 1 and 250),
  persona_id bigint references public.personas(id) on delete set null,
  bitacora_id bigint references public.bitacoras(id) on delete set null,
  fecha timestamptz not null default now()
);

create or replace function public.actualizar_timestamp_bitacora()
returns trigger
language plpgsql
as $$
begin
  new.actualizada = now();
  return new;
end;
$$;

drop trigger if exists trg_bitacoras_actualizada on public.bitacoras;
create trigger trg_bitacoras_actualizada
before update on public.bitacoras
for each row execute function public.actualizar_timestamp_bitacora();

create index if not exists idx_bitacoras_persona_id on public.bitacoras(persona_id);
create index if not exists idx_bitacoras_google_doc_id on public.bitacoras(google_doc_id);
create index if not exists idx_eventos_inicio on public.eventos(inicio);
create index if not exists idx_actividad_fecha on public.actividad(fecha desc, id desc);

-- Habilitar RLS desde el inicio (sin políticas abiertas: se configuran en 0002_auth_y_rls.sql).
alter table public.personas enable row level security;
alter table public.bitacoras enable row level security;
alter table public.eventos enable row level security;
alter table public.actividad enable row level security;
