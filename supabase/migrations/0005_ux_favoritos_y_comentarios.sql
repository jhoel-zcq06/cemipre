-- Migración 0005: Favoritos por trabajador y comentarios internos en BD (UX-01)

create table if not exists public.favoritos_trabajador (
  id bigint generated by default as identity primary key,
  trabajador_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  persona_id bigint not null references public.personas(id) on delete cascade,
  creado timestamptz not null default now(),
  unique (trabajador_id, persona_id)
);

create table if not exists public.comentarios_internos (
  id bigint generated by default as identity primary key,
  persona_id bigint not null references public.personas(id) on delete cascade,
  bitacora_id bigint references public.bitacoras(id) on delete cascade,
  autor_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  autor_nombre text not null default '',
  contenido text not null check (char_length(trim(contenido)) between 1 and 1500),
  creado timestamptz not null default now()
);

create index if not exists idx_favoritos_trabajador on public.favoritos_trabajador(trabajador_id);
create index if not exists idx_comentarios_persona on public.comentarios_internos(persona_id, creado desc);

alter table public.favoritos_trabajador enable row level security;
alter table public.comentarios_internos enable row level security;

drop policy if exists favoritos_select_propio on public.favoritos_trabajador;
create policy favoritos_select_propio
on public.favoritos_trabajador for select
using (public.es_trabajador_autorizado() and trabajador_id = auth.uid());

drop policy if exists favoritos_insert_propio on public.favoritos_trabajador;
create policy favoritos_insert_propio
on public.favoritos_trabajador for insert
with check (public.es_trabajador_autorizado() and trabajador_id = auth.uid());

drop policy if exists favoritos_delete_propio on public.favoritos_trabajador;
create policy favoritos_delete_propio
on public.favoritos_trabajador for delete
using (public.es_trabajador_autorizado() and trabajador_id = auth.uid());

drop policy if exists comentarios_select_autorizado on public.comentarios_internos;
create policy comentarios_select_autorizado
on public.comentarios_internos for select
using (public.es_trabajador_autorizado());

drop policy if exists comentarios_insert_autorizado on public.comentarios_internos;
create policy comentarios_insert_autorizado
on public.comentarios_internos for insert
with check (public.es_trabajador_autorizado() and autor_id = auth.uid());

drop policy if exists comentarios_delete_autor_o_admin on public.comentarios_internos;
create policy comentarios_delete_autor_o_admin
on public.comentarios_internos for delete
using (public.es_admin() or (public.es_trabajador_autorizado() and autor_id = auth.uid()));
