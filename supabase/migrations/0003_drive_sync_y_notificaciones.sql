-- Migración 0003: Metadatos de sincronización Google Drive y registro de notificaciones (DRV-03 / NOT-02 / AI-01)

alter table public.personas
  add column if not exists drive_folder_id text not null default '';

alter table public.bitacoras
  add column if not exists drive_modified_time timestamptz,
  add column if not exists drive_revision_id text not null default '',
  add column if not exists ultimo_resumen text not null default '',
  add column if not exists ultimo_resumen_fecha timestamptz,
  add column if not exists estado_sync text not null default 'pendiente';

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'bitacoras_estado_sync_check'
  ) then
    alter table public.bitacoras
      add constraint bitacoras_estado_sync_check
      check (estado_sync in ('pendiente', 'sincronizada', 'sin_permiso', 'no_encontrada', 'sin_enlace'));
  end if;
end $$;

create table if not exists public.drive_sync_state (
  id text primary key default 'global',
  start_page_token text not null default '',
  ultima_sincronizacion timestamptz,
  ultimo_estado text not null default '',
  actualizado timestamptz not null default now()
);

insert into public.drive_sync_state (id)
values ('global')
on conflict (id) do nothing;

create table if not exists public.notificaciones_enviadas (
  id bigint generated by default as identity primary key,
  bitacora_id bigint references public.bitacoras(id) on delete cascade,
  persona_id bigint references public.personas(id) on delete set null,
  destinatario_email text not null,
  estado text not null check (estado in ('enviada', 'error', 'omitida')),
  detalle_error text not null default '',
  drive_revision_id text not null default '',
  enviada_en timestamptz not null default now()
);

create index if not exists idx_personas_drive_folder_id on public.personas(drive_folder_id);
create index if not exists idx_notificaciones_bitacora_fecha on public.notificaciones_enviadas(bitacora_id, enviada_en desc);
create index if not exists idx_notificaciones_fecha on public.notificaciones_enviadas(enviada_en desc, id desc);

alter table public.drive_sync_state enable row level security;
alter table public.notificaciones_enviadas enable row level security;

drop policy if exists drive_sync_state_select_autorizado on public.drive_sync_state;
create policy drive_sync_state_select_autorizado
on public.drive_sync_state for select
using (public.es_trabajador_autorizado());

drop policy if exists notificaciones_select_autorizado on public.notificaciones_enviadas;
create policy notificaciones_select_autorizado
on public.notificaciones_enviadas for select
using (public.es_trabajador_autorizado());
